// Построить контур
// ---
void WorkContour()
{
  Contour( 1 );  // Задание контура, style -	стиль линии ( 1 - основная, 2 - тонкая,
                 // 3 - осевая, 4 - штриховая,  5 - волнистая, 6 - утолщенная,
                 // 7 - штрихпунктирная с двумя точками,  8 - осевая основная,
                 // 9 - штриховая основная, 10 - осевая толстая,
                 // 11 - тонкая, включаемая в штриховку )
    LineSeg( 20, 30, 50, 30, 1 );
    ArcByPoint( 50, 20, 10, 50, 30, 50, 10, -1, 1 );
    // Вложенный контур
    Contour( 2 );
      LineSeg( 50, 10, 20, 10, 1 );
      ArcByPoint( 20, 20, 10, 20, 10, 20, 30, -1, 1 );
    EndObj();
  reference rContour = EndObj(); // Функция EndObj возвращает указатель на созданный объект контур
  
  // Подсветить контур
	LightObj( rContour, 1 );
	MessageT( _T("Снять выделение контура") );
  // Снять выделение контура 
  LightObj( rContour, 0 );
  
  // Создание группы объектов, type - тип группы ( 0 - определяет модельный, 1 - временный )
  reference g = NewGroup( 0 );
  EndGroup(); // Завершить создание группы объектов
  
  // Добавить новый объект в группу
  AddObjGroup( g, rContour );
  MoveObj( g, 10, 10 ); // Сдвинуть группу на 10 по оси OX, на 10 по оси OY
}


