// Допуск формы
// ---
void WorkTolerance()
{
  ToleranceParam parTolerance; // Структура параметров обозначения допуска формы и расположения поверхностей  
  MathPointParam parPoint;     // Структура параметров математической точки
 
  // Заполняем параметры 1-ой опоры
  // Создать массив для хранения точек 1-ой опоры
  parTolerance.branch1.pMathPoint = CreateArray( POINT_ARR,  0 );
  parTolerance.branch1.arrowType  = 2; // Тип опоры ( 0 - нет опоры, 1 - треугольник, 2 - стрелка )
  parTolerance.branch1.tCorner    = 1; // Число от 1 до 8, определяющее точку выхода "опоры" из таблицы
  
  // Координаты точки опоры
  parPoint.x = 40; 
  parPoint.y = 10;
  // Добавим точку опоры в массив, элемент добавляется в конец массива
  AddArrayItem( parTolerance.branch1.pMathPoint, -1, &parPoint, sizeof( parPoint ) );
  
  // Заполняем параметры 2-ой опоры
  // Создать массив для хранения точек 2-ой опоры
  parTolerance.branch2.pMathPoint = CreateArray( POINT_ARR,  0 );
  parTolerance.branch2.arrowType  = 1; // Тип опоры ( 0 - нет опоры, 1 - треугольник, 2 - стрелка )
  parTolerance.branch2.tCorner    = 5; // Число от 1 до 8, определяющее точку выхода "опоры" из таблицы
  
  // Координаты первой точки опоры
  parPoint.x = 100; 
  parPoint.y = 50;   
  // Добавим 1-ю точку опоры в массив, элемент добавляется в конец массива
  AddArrayItem( parTolerance.branch2.pMathPoint, -1, &parPoint, sizeof( parPoint ) );  
  
  // Координаты второй точки опоры
  parPoint.x = 100; 
  parPoint.y = 10;  
  // Добавим 2-ю точку опоры в массив, элемент добавляется в конец массива
  AddArrayItem( parTolerance.branch2.pMathPoint, -1, &parPoint, sizeof( parPoint ) );
 
  // Координаты базовой точки
  parTolerance.x    = 40; 
  parTolerance.y    = 40; 
  parTolerance.type = 0;  // Ориентация таблицы допуска ( 0 - горизонтально, 1 - вертикально ) 
  // Создание обозначения допуска формы, состоящей из таблицы ( в общем случае 10х10 ) и двух опор 
  Tolerance( &parTolerance );
    // Определить номер графы штампа ( 1-я графа ) 
    ColumnNumber( 1 );
    // Задание подстроки графы штампа
    // Спецзнак  
    int symbol = 26;
		TextLineT( SPECIAL_SYMBOL, // Значения свойств, устанавливаемые двоичными флагами
							 SPECIAL,        // Тип свойства
							 &symbol,        // Указатель на значение свойства
							 _T("") );           // Строка
    
    // 2-я графа
    ColumnNumber( 2 );
		TextLineT ( NEW_LINE, 0, 0, _T("111") );
    
    // 3-я графа
    ColumnNumber( 3 );
		TextLineT ( NEW_LINE, 0, 0, _T("222") );
    
    // 11-я графа
    ColumnNumber( 11 );
    // Спецзнак 
    symbol = 23;
		TextLineT ( SPECIAL_SYMBOL, SPECIAL, &symbol, _T("") );
    
    // 12-я графа
    ColumnNumber( 12 );
		TextLineT( NEW_LINE, 0, 0, _T("333") );

		// 13-я графа
		ColumnNumber( 13 );
		TextLineT( NEW_LINE, 0, 0, _T("444") );
  reference rTolerance = EndObj(); // Функция EndObj возвращает указатель на созданный объект допуска формы 

  // Подсветить допуск формы
  LightObj( rTolerance, 1 );
	MessageT( _T("Снять выделение допуска формы") );
  // Снять выделение допуска формы 
  LightObj( rTolerance, 0 ); 
  
  DeleteArray( parTolerance.branch2.pMathPoint ); // Удалить динамический массив точек 2-ой опоры
  DeleteArray( parTolerance.branch1.pMathPoint ); // Удалить динамический массив точек 1-ой опоры
}


//-------------------------------------------------------------------------------
// Построить эквидистанту
// ---
void DrawEquidistant()
{
  EquidistantParam parEquidistant; // Структура параметров эквидистанты
  
  parEquidistant.side     = 2; // Признак, с какой стороны строить эквидистанту ( 0 - слева по направлению,
                               // 1 - справа по направлению, 2 - с двух сторон )
  parEquidistant.cutMode  = 0; // Тип обхода углов контура ( 0 - обход срезом, 1 - обход дугой )
  parEquidistant.degState = 0; // Флаг разрешения вырожденных сегментов эквидистанты ( 0 - вырожденные
                               // сегменты запрещены, 1 - вырожденные сегменты разрешены )
  parEquidistant.radRight = 5; // Радиус эквидистанты
  parEquidistant.radLeft  = 3; // Радиус эквидистанты
  parEquidistant.style    = 1; // Cтиль линии ( 1 - основная, 2 - тонкая, 3 - осевая, 4 - штриховая, 
                               // 5 - волнистая, 6 - утолщенная, 7 - штрихпунктирная с двумя точками, 
                               // 8 - осевая основная, 9 - штриховая основная, 10 - осевая толстая,
                               // 11 - тонкая, включаемая в штриховку )
 
  // Структура параметров запроса к системе
	RequestInfoT info;
  memset( &info, 0, sizeof( info ) );
  
  // Строка или идентификатор меню состава команд 
	info.prompt = _T("Укажите объект");
  
  // Координаты точки ввода
  double x, y;  
  
  // Интерактивный ввод точки или команды
  while( CursorExT( &info, &x, &y, 0, NULL ) )
  {
    // Найти ближайший к заданной точке объект вида
    parEquidistant.geoObj = FindObj( x, y,  // Координаты точки
                                     1e6 ); // Размер стороны квадрата-ловушки с центром в точке x,y
    // Проверить существование объекта
    if ( ExistObj( parEquidistant.geoObj ) )
    { 
      // Создание эквидистанты
      reference rEquidistant = Equidistant( &parEquidistant );
      
      // Подсветить эквидистанту
      LightObj( rEquidistant, 1 );
			MessageT( _T("Снять выделение эквидистанты") );
      // Снять выделение эквидистанты 
      LightObj( rEquidistant, 0 ); 
    }
    else
			ErrorT( _T("Объект не найден") );
  }
}


